// Radiotelephony is a closed, standardised grammar (ICAO Doc 9432 / FAA JO 7110.65), so a phrase table is both more
// accurate and more predictable than a general machine translation, and it works offline with zero latency. Callsigns,
// airport / taxiway names, runway designators, frequencies and numbers are left untouched; station names (Tower,
// Ground, Approach, Departure, Delivery, Information) stay in English because they are the facility's call name — that
// is how Indonesian pilots and controllers actually say them. Only the transcript is translated: the spoken audio is
// always English, as it is on the real frequency (ICAO Annex 10 Vol. II, 5.2.1.2).
//
// Hand-written crew / PA lines carry their own `textId` (see comms.ts) and never pass through here.
