// Most specific phrase first: sorting by pattern length makes the longest (most specific) rule win, so the table can be
// grouped by topic instead of hand-ordered.
RULES.sort((a, b) => b[0].source.length - a[0].source.length);

const SENTENCE_START = /(^|[.!?]\s+|:\s+)(\p{Ll})/gu;
/** Translate one radio / PA transcript line into Indonesian (phrase table; unknown words are kept as-is). */
export function translateId(text: string): string {
  let t = text;
  for (const [re, rep] of RULES) t = t.replace(re, rep);
  // 1,500 kaki -> 1.500 kaki (Indonesian thousands separator)
  t = t.replace(/(\d),(\d{3})(?= (?:kaki|knot))/g, '$1.$2');
  return t.replace(/\s+/g, ' ').replace(/\s+([,.])/g, '$1').replace(SENTENCE_START, (_m, a: string, b: string) => a + b.toUpperCase());
}

export type TranscriptLang = 'en' | 'id';
/** The transcript text for the chosen language: curated Indonesian when the line has one, rule-based otherwise. */
export function transcriptText(m: { text: string; textId?: string }, lang: TranscriptLang): string {
  return lang === 'id' ? (m.textId ?? translateId(m.text)) : m.text;
}
