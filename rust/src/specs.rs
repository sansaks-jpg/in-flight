//! Aircraft definition. The original project is an Airbus A320-200 simulator (the Cessna/ATR entries in
//! `src/sim/specs.ts` are reference data only and filtered out), so the Rust port carries the A320 spec 1:1.
//!
//! Dimensions / weights are the manufacturer's published values (A320-200, CFM56-5B):
//! L 37.57 m, b 34.10 m, H 11.76 m, S 122.6 m², MTOW 78 000 kg, wheelbase 12.64 m, track 7.59 m, 2 x 120 kN.
//!
//! Body frame: +X right, +Y up, -Z forward, origin = CG. Gear / hull points are CG-relative.

